#include <iostream>
using namespace std;

// implementacion en C++
int main()
{
    int arr[] = {1, 2, 3, 4, 5};
    int n = 5;

    cout << "Los elementos del array son:" << endl;
    for (int i = 0; i < n; i++)
    {
        cout << arr[i] << " "; // mostrando los elementos del array separados por espacios especiales
    }

    return 0;
}
