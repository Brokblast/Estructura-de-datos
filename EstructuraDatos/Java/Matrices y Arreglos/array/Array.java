// implementacion en Java
public class Array {
    public static void main(String[] args) {
        int[] arr = {1, 2, 3, 4, 5};
        System.out.println("Los elementos del array son:");
        for (int element : arr) {
            System.out.print(element + " "); // mostrando los elementos del array separados por espacios especiales
        }
    }
}
